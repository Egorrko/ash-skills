// Dead client code: unused files, exports and dependencies.
// LiveVue pages are named by strings in Elixir (<.vue v-component="X">) and Vite finds
// them by a glob, which knip does not read, so the entry list is built here.
import { readFileSync, readdirSync } from "node:fs"
import { join, relative } from "node:path"
import type { KnipConfig } from "knip"

const root = import.meta.dirname

const walk = (dir: string, test: (f: string) => boolean): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap(e => {
    const p = join(dir, e.name)
    if (e.isDirectory()) return e.name === "node_modules" ? [] : walk(p, test)
    return test(p) ? [p] : []
  })

const names = new Set<string>()
for (const f of walk(join(root, "lib"), f => /\.(ex|heex)$/.test(f))) {
  for (const m of readFileSync(f, "utf8").matchAll(/v-component="([^"]+)"/g)) names.add(m[1]!)
}

// Resolved the way LiveVue's findComponent does: a path suffix, without .vue or /index.vue.
const key = (f: string) => f.replace(/\.vue$/, "").replace(/\/index$/, "")
const pages = walk(join(root, "assets/vue"), f => f.endsWith(".vue"))
  .map(f => relative(root, f))
  .filter(f => [...names].some(n => key(f) === n || key(f).endsWith("/" + n)))

const config: KnipConfig = {
  entry: [
    "assets/js/app.{js,ts}",
    // LiveVue's SSR entry, built by Vite for the server
    "assets/js/server.{js,ts}",
    "assets/css/app.css",
    "assets/vue/index.ts",
    ...pages,
    // shadcn-vue primitives are copied whole: an unused variant is not dead product code
    "assets/components/ui/**/*.{ts,vue}",
    "assets/**/*.test.ts",
    "bin/**/*.mjs",
  ],
  project: ["assets/**/*.{js,mjs,ts,vue,css}", "bin/**/*.mjs"],
  // vue comes through live_vue rather than package.json, so knip does not turn its
  // Vue compiler on by itself; without it every .vue file goes unread.
  compilers: { vue: true },
  // Called from mix, not from JS: the Vite build, the contract generator, the type check.
  // phoenix-colocated is generated by mix compile into _build.
  ignoreDependencies: ["phoenix_vite", "vue-component-meta", "vue-tsc", "phoenix-colocated"],
  ignoreExportsUsedInFile: true,
  vite: { config: ["assets/vite.config.mjs"] },
}

export default config
